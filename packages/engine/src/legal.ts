import { ACTION_REACTIONS, applyAction, ATTACK_REACTIONS, braceOf, canDeploy, canPlayCard, cityLedger, costOf, incomeOf, other, requireMainPhase, ROLE_BEATS, SNARE_DAMAGE, trapRole, trapsOf, trapWallOf } from './engine';
import { RULES } from './data';
import { getDistrict } from './districts';
import type { Action, CardDef, GameState, PlayerId, PlayerState, UnitRole } from './types';

/** All targets a card could legally take (undefined entry = no target needed). */
export function targetsFor(st: GameState, pid: PlayerId, card: CardDef): (string | undefined)[] {
  if (!card.target || card.target === 'none') return [undefined];
  const owner = card.target === 'enemyBuilding' ? st.players[other(pid)] : st.players[pid];
  return owner.buildings.map((b) => b.uid);
}

/** Main-phase actions excluding attacks (attack combinations are generated by callers). */
export function listPlays(st: GameState, pid: PlayerId): Action[] {
  if (st.phase !== 'main' || st.active !== pid) return [];
  const out: Action[] = [];
  const p = st.players[pid];
  const seen = new Set<string>();
  for (const c of p.hand) {
    if (c.cardId === '?' || seen.has(c.cardId)) continue;
    if (canPlayCard(st, pid, c.uid)) continue;
    seen.add(c.cardId);
    for (const t of targetsFor(st, pid, getCard(c.cardId))) out.push({ type: 'play', uid: c.uid, targetUid: t });
  }
  const sig = getCiv(p.civ).signature;
  if (!p.signatureUsed && p.momentum >= sig.cost) out.push({ type: 'signature' });
  return out;
}

export function readyAttackers(st: GameState, pid: PlayerId): string[] {
  return st.players[pid].units.filter((u) => u.ready && !u.attacked && !(getCard(u.cardId).keywords ?? []).includes('guard')).map((u) => u.uid);
}

/** Reactions the defender could legally play right now. */
export function playableReactions(st: GameState, pid: PlayerId): string[] {
  if (st.phase !== 'response' || !st.pending) return [];
  const allowed = st.pending.kind === 'attack' ? ATTACK_REACTIONS : ACTION_REACTIONS;
  const p = st.players[pid];
  return p.hand.filter((c) => {
    if (c.cardId === '?') return false;
    const card = getCard(c.cardId);
    return card.kind === 'reaction' && !!card.reaction && allowed.includes(card.reaction) && p.prosperity >= card.cost;
  }).map((c) => c.uid);
}

/** Call to Arms: unit cards in hand that could rush into this fight as a blocker (paid from Prosperity). */
export function musterable(st: GameState, pid: PlayerId): string[] {
  if (st.phase !== 'response' || st.pending?.kind !== 'attack') return [];
  const p = st.players[pid];
  if (p.units.length >= RULES.maxUnits) return [];
  return p.hand.filter((c) => {
    if (c.cardId === '?') return false;
    const card = getCard(c.cardId);
    return card.kind === 'unit' && canDeploy(p, card) && p.prosperity >= costOf(p, card);
  }).map((c) => c.uid);
}

export function availableBlockers(st: GameState, pid: PlayerId): string[] {
  if (st.phase !== 'response' || st.pending?.kind !== 'attack') return [];
  return st.players[pid].units.filter((u) => !u.blocked && !u.attacked).map((u) => u.uid);
}

/** What this card does if it springs from under a building. */
export function trapText(card: CardDef): string {
  switch (trapRole(card)) {
    case 'garrison': return `Bursts out and fights as a defender for that one battle (${card.str ?? 1} Strength). Also catches schemers.`;
    case 'reaction': return `${card.name} takes effect for free when the spot is hit.`;
    case 'wall': return `Stands as a wall for that one fight, soaking ${trapWallOf(card)} damage.`;
    case 'snare': return `A snare: ${SNARE_DAMAGE} damage to every attacker before the clash. Also catches schemers.`;
    case 'brace': return `Braces the spot: soaks ${braceOf(card)} damage from that attack or scheme.`;
  }
}

/** Spots where `pid` can hide a card right now ('city' and building uids with room). */
export function tuckSpots(st: GameState, pid: PlayerId): string[] {
  if (requireMainPhase(st, pid)) return [];
  const p = st.players[pid];
  const count = (at: string) => trapsOf(p).filter((t) => t.at === at).length;
  return ['city', ...p.buildings.map((b) => b.uid)].filter((at) => count(at) < RULES.trapsPerSpot);
}

