type Tiers = [string[], string[], string[], string[], string[]];
function decksFor(civ: CivId): Record<Family, Tiers> {
  const build = (f: Family) => SHARED_TIERS[f].map((shared, i) => {
    const own = OWN[civ][f][i];
    return [...shared, own, ...(i === 4 && f === 'civ' ? [] : [own])]; // two copies, one of each wonder
  }) as Tiers;
  return { civ: build('civ'), mil: build('mil') };
}

